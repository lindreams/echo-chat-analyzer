"""Regenerate the bundled Emoji 18.0 table from a local official data directory.

Download emoji-test.txt from https://www.unicode.org/Public/18.0.0/emoji/,
emoji-variation-sequences.txt from /Public/18.0.0/ucd/emoji/, and LICENSE.txt
from https://www.unicode.org/license.txt. No network is used by this script.
Run: .venv/Scripts/python.exe scripts/generate_unicode_emoji.py <directory>
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


def generate(directory: Path) -> str:
    sources = {
        name: (directory / name).read_bytes()
        for name in ("emoji-test.txt", "emoji-variation-sequences.txt", "LICENSE.txt")
    }
    emoji_test = sources["emoji-test.txt"].decode("utf-8")
    variations = sources["emoji-variation-sequences.txt"].decode("utf-8")
    if "# Version: 18.0\n" not in emoji_test or "Version: 18.0" not in variations:
        raise ValueError("Expected official Emoji 18.0 input files")
    sequences = set()
    for line in emoji_test.splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        points, qualification = (part.strip() for part in body.split(";"))
        if qualification != "component":
            sequences.add(tuple(int(point, 16) for point in points.split()))
    for line in variations.splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        points, style, _ = (part.strip() for part in body.split(";"))
        sequence = tuple(int(point, 16) for point in points.split())
        # Digits/#/* alone (including VS16) are not expressions. Only keycaps
        # from emoji-test are accepted for those bases.
        if style == "emoji style" and sequence[0] not in (*range(0x30, 0x3A), 0x23, 0x2A):
            sequences.add(sequence)
    license_text = sources["LICENSE.txt"].decode("utf-8").strip()
    hashes = "\n".join(
        f"# {name}: {hashlib.sha256(data).hexdigest()}"
        for name, data in sources.items()
    )
    lines = "\n".join(" ".join(f"{point:X}" for point in item) for item in sorted(sequences))
    return (
        '# Generated by scripts/generate_unicode_emoji.py; do not edit by hand.\n'
        '# Sources: https://www.unicode.org/Public/18.0.0/emoji/emoji-test.txt\n'
        '# https://www.unicode.org/Public/18.0.0/ucd/emoji/emoji-variation-sequences.txt\n'
        + hashes + '\n'
        + '"""Derived Unicode data, with its upstream license:\n\n'
        + license_text + '\n"""\n\n'
        + 'UNICODE_EMOJI_VERSION = "18.0"\n\n'
        + 'EMOJI_CODEPOINT_SEQUENCES = """\\\n' + lines + '\n"""\n'
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / "src/qq_chat_analyzer/_unicode_emoji_data.py"
    generated = generate(args.directory)
    if args.check:
        if output.read_text(encoding="utf-8") != generated:
            raise SystemExit("Bundled Emoji data differs from regenerated data")
    else:
        output.write_text(generated, encoding="utf-8", newline="\n")
